// Pre-indexed map for instant O(1) corpus rank lookup
const CORPUS_RANK_MAP = new Map<string, number>();
TOP_ARABIC_CORPUS_WORDS.forEach((word, index) => {
  if (!CORPUS_RANK_MAP.has(word)) {
    CORPUS_RANK_MAP.set(word, index + 1);
  }
});

/**
 * Returns rank in the top corpus (1 to 2000) or undefined if not in the top 2000.
 */
export function getCorpusWordRank(word: string): number | undefined {
  return CORPUS_RANK_MAP.get(word);
}

/**
 * Categorizes frequency percentile based on corpus rank
 */
export function getCorpusFrequencyCategory(
  rank?: number
): 'Top 100' | 'Top 500' | 'Top 1000' | 'Top 2000' | 'Infrequent' {
  if (!rank) return 'Infrequent';
  if (rank <= 100) return 'Top 100';
  if (rank <= 500) return 'Top 500';
  if (rank <= 1000) return 'Top 1000';
  return 'Top 2000';
}

/**
 * Generates an array of words filtered from the top corpus
 */
export function getTopCorpusWords(
  count: number = 100,
  options?: {
    minLength?: number;
    maxLength?: number;
    shuffle?: boolean;
    startRank?: number;
  }
): string[] {
  const { minLength = 2, maxLength = 8, shuffle = false, startRank = 1 } = options || {};

  let pool = TOP_ARABIC_CORPUS_WORDS.slice(Math.max(0, startRank - 1));

  if (minLength > 0 || maxLength > 0) {
    pool = pool.filter((w) => w.length >= minLength && w.length <= maxLength);
  }

  let result = pool.slice(0, count);

  if (shuffle) {
    // Fisher-Yates shuffle
    result = [...result];
    for (let i = result.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [result[i], result[j]] = [result[j], result[i]];
    }
  }

  return result;
}
